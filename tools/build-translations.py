#!/usr/bin/env python3
"""Generate the web app's translation bundles from the .properties files.

The web app does not read .properties files. It loads one JavaScript file per
language, js/properties_keys_<tag>.js, which fills the global
__GGB__keysVar[<tag>] with three dictionaries: command, menu and symbols
(see LocalizationW). The English bundle is also compiled into the app through
GuiResources. This script writes those bundles from the Java-side
.properties files, so both platforms share one source of truth.

Usage: tools/build-translations.py [--check]
With --check it fails if a bundle on disk is out of date.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROPS = ROOT / "source/shared/common-jre/src/main/resources/org/geogebra/common/jre/properties"
OUT = ROOT / "source/web/web/src/main/resources/org/geogebra/web/pub/js"
GROUPS = ("command", "menu", "symbols")
HEADER = """/*
 * Locus translation bundle for {tag}.
 * Generated by tools/build-translations.py from the .properties files in
 * source/shared/common-jre; edit those instead.
 * SPDX-License-Identifier: EUPL-1.2
 */
"""


def parse_properties(text):
    """Parse Java .properties text (UTF-8, backslash continuations, \\uXXXX)."""
    result = {}
    logical = []
    pending = None
    for raw in text.splitlines():
        stripped = raw.lstrip()
        if pending is None and (not stripped or stripped[0] in "#!"):
            continue
        line = stripped if pending is None else pending + stripped
        # an odd number of trailing backslashes continues the line
        trailing = len(line) - len(line.rstrip("\\"))
        if trailing % 2 == 1:
            pending = line[:-1]
            continue
        pending = None
        logical.append(line)
    if pending is not None:
        logical.append(pending)
    for line in logical:
        match = re.match(r"((?:\\.|[^=:\s\\])*)\s*[=:\s]\s*(.*)$", line)
        if not match:
            key, value = line, ""
        else:
            key, value = match.group(1), match.group(2)
        result[unescape(key)] = unescape(value)
    return result


def unescape(value):
    def repl(match):
        char = match.group(1)
        if char.startswith("u"):
            return chr(int(char[1:], 16))
        return {"t": "\t", "n": "\n", "r": "\r", "f": "\f"}.get(char, char)

    return re.sub(r"\\(u[0-9a-fA-F]{4}|.)", repl, value)


def languages():
    tags = set()
    for path in PROPS.glob("menu*.properties"):
        stem = path.stem
        tags.add("en" if stem == "menu" else stem[len("menu_"):])
    return sorted(tags)


def bundle(tag):
    suffix = "" if tag == "en" else "_" + tag
    parts = [HEADER.format(tag=tag),
             "/* globals __GGB__keysVar */\n",
             "__GGB__keysVar = window.__GGB__keysVar || {};\n",
             f'__GGB__keysVar["{tag}"] = {{}};\n']
    for group in GROUPS:
        path = PROPS / f"{group}{suffix}.properties"
        data = parse_properties(path.read_text(encoding="utf-8")) if path.exists() else {}
        encoded = json.dumps(json.dumps(data, ensure_ascii=False, sort_keys=True), ensure_ascii=False)
        parts.append(f'__GGB__keysVar["{tag}"].{group} = JSON.parse({encoded});\n')
    return "".join(parts)


def main():
    check = "--check" in sys.argv
    stale = []
    for tag in languages():
        target = OUT / f"properties_keys_{tag.replace('_', '-')}.js"
        content = bundle(tag)
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(target.name)
        else:
            target.write_text(content, encoding="utf-8")
    if stale:
        sys.exit("Out of date, run tools/build-translations.py: " + ", ".join(stale))


if __name__ == "__main__":
    main()
